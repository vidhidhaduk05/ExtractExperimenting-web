"""Clarification Questions Router.

Provides endpoints for listing, retrieving, answering, batch-answering, dismissing,
and summarizing mid-pipeline clarification questions generated by the AI screener.
"""
from __future__ import annotations

import json
from typing import Any, Optional

from fastapi import APIRouter, Depends, HTTPException, Query

from database import get_db
from dependencies import check_project_access, get_current_user_optional
from models import (
    BatchClarificationAnswerRequest,
    ClarificationAnswerRequest,
    ClarificationAnswerResponse,
    ClarificationOption,
    ClarificationQuestionResponse,
    ClarificationStatsResponse,
)
from services.clarification_resolver import resolve_clarification
from services.db_backend import DBBackend

router = APIRouter(prefix="/api", tags=["clarification"])


def _row_to_clarification_response(row: Any) -> ClarificationQuestionResponse:
    r = dict(row)
    raw_opts = []
    if r.get("options_json"):
        try:
            raw_opts = json.loads(r["options_json"])
        except Exception:
            raw_opts = []

    options = []
    for opt in raw_opts:
        if isinstance(opt, dict) and "value" in opt and "label" in opt:
            options.append(ClarificationOption(value=str(opt["value"]), label=str(opt["label"])))
        elif isinstance(opt, str):
            options.append(ClarificationOption(value=opt.lower().replace(" ", "_"), label=opt))

    return ClarificationQuestionResponse(
        question_id=r["question_id"],
        study_id=r["study_id"],
        project_id=r["project_id"],
        stage=r.get("stage", "ta"),
        question_type=r.get("question_type", "study_design"),
        pico_aspect=r.get("pico_aspect", "study_design"),
        question_text=r.get("question_text", ""),
        options=options,
        context_excerpt=r.get("context_excerpt", ""),
        ai_interim_decision=r.get("ai_interim_decision", "uncertain"),
        ai_interim_reason=r.get("ai_interim_reason", ""),
        status=r.get("status", "pending"),
        answer=r.get("answer", "") or "",
        answer_label=r.get("answer_label", "") or "",
        answer_freetext=r.get("answer_freetext", "") or "",
        answered_by=r.get("answered_by", "") or "",
        answered_at=r.get("answered_at", "") or "",
        final_decision=r.get("final_decision", "") or "",
        final_confidence=float(r.get("final_confidence", 0.0) or 0.0),
        final_reason_text=r.get("final_reason_text", "") or "",
        created_at=r.get("created_at", "") or "",
        is_tracked=bool(r.get("is_tracked", 0)),
        study_title=r.get("study_title", "") or "",
        study_authors=r.get("study_authors", "") or "",
        study_abstract=r.get("study_abstract", "") or "",
    )


@router.get("/projects/{project_id}/clarifications", response_model=list[ClarificationQuestionResponse])
async def list_clarifications(
    project_id: str,
    status: Optional[str] = Query("pending", description="Filter by status: pending, answered, expired, all"),
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """List clarification questions for a project."""
    check_project_access(conn, project_id, user)

    base_query = """
        SELECT cq.*, s.title as study_title, s.authors as study_authors, s.abstract as study_abstract
        FROM clarification_questions cq
        LEFT JOIN studies s ON cq.study_id = s.study_id
        WHERE cq.project_id = ?
    """

    if status and status.lower() != "all":
        query = f"{base_query} AND cq.status = ? ORDER BY cq.created_at DESC"
        rows = conn.execute(query, (project_id, status.lower())).fetchall()
    else:
        query = f"{base_query} ORDER BY cq.created_at DESC"
        rows = conn.execute(query, (project_id,)).fetchall()

    return [_row_to_clarification_response(row) for row in rows]


@router.get("/projects/{project_id}/clarifications/stats", response_model=ClarificationStatsResponse)
async def clarification_stats(
    project_id: str,
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Get clarification question queue statistics for a project."""
    check_project_access(conn, project_id, user)

    rows = conn.execute(
        "SELECT status, question_type, stage FROM clarification_questions WHERE project_id = ?",
        (project_id,),
    ).fetchall()

    pending = 0
    answered = 0
    expired = 0
    by_type: dict[str, int] = {}
    by_stage: dict[str, int] = {}

    for row in rows:
        r = dict(row)
        st = r.get("status", "pending")
        if st == "pending":
            pending += 1
        elif st == "answered":
            answered += 1
        elif st == "expired":
            expired += 1

        qt = r.get("question_type") or "other"
        by_type[qt] = by_type.get(qt, 0) + 1

        stage = r.get("stage") or "ta"
        by_stage[stage] = by_stage.get(stage, 0) + 1

    return ClarificationStatsResponse(
        project_id=project_id,
        pending=pending,
        answered=answered,
        expired=expired,
        by_type=by_type,
        by_stage=by_stage,
    )


@router.get("/clarifications/{question_id}", response_model=ClarificationQuestionResponse)
async def get_single_clarification(
    question_id: str,
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Get a single clarification question by ID."""
    row = conn.execute(
        """
        SELECT cq.*, s.title as study_title, s.authors as study_authors, s.abstract as study_abstract
        FROM clarification_questions cq
        LEFT JOIN studies s ON cq.study_id = s.study_id
        WHERE cq.question_id = ?
        """,
        (question_id,),
    ).fetchone()

    if not row:
        raise HTTPException(status_code=404, detail="Clarification question not found")

    q_dict = dict(row)
    check_project_access(conn, q_dict["project_id"], user)
    return _row_to_clarification_response(row)


@router.post("/clarifications/{question_id}/answer", response_model=ClarificationAnswerResponse)
async def answer_clarification(
    question_id: str,
    req: ClarificationAnswerRequest,
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Submit an answer to a clarification question, triggering AI resolution."""
    row = conn.execute(
        "SELECT * FROM clarification_questions WHERE question_id = ?",
        (question_id,),
    ).fetchone()

    if not row:
        raise HTTPException(status_code=404, detail="Clarification question not found")

    q_dict = dict(row)
    check_project_access(conn, q_dict["project_id"], user)

    if q_dict["status"] != "pending":
        raise HTTPException(status_code=400, detail=f"Question is already {q_dict['status']}")

    reviewer = req.answered_by or (user.get("username") if user else "human_reviewer")

    try:
        res = resolve_clarification(
            question_id=question_id,
            answer=req.answer,
            answer_label=req.answer_label,
            answer_freetext=req.answer_freetext,
            answered_by=reviewer,
            db=conn,
        )
        return ClarificationAnswerResponse(**res)
    except KeyError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to resolve clarification: {str(e)}")


@router.post("/projects/{project_id}/clarifications/batch-answer", response_model=list[ClarificationAnswerResponse])
async def batch_answer_clarifications(
    project_id: str,
    req: BatchClarificationAnswerRequest,
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Answer multiple clarification questions in batch."""
    check_project_access(conn, project_id, user)

    results: list[ClarificationAnswerResponse] = []
    reviewer = req.answered_by or (user.get("username") if user else "human_reviewer")

    for item in req.answers:
        try:
            res = resolve_clarification(
                question_id=item.question_id,
                answer=item.answer,
                answer_label=item.answer_label,
                answer_freetext=item.answer_freetext,
                answered_by=reviewer,
                db=conn,
            )
            results.append(ClarificationAnswerResponse(**res))
        except Exception:
            # Skip failures or handle individually
            pass

    return results


@router.delete("/clarifications/{question_id}")
async def dismiss_clarification(
    question_id: str,
    dismiss_reason: str = Query("", description="Optional reason for dismissing question"),
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Dismiss a clarification question without answering (sets to expired, study to uncertain)."""
    row = conn.execute(
        "SELECT * FROM clarification_questions WHERE question_id = ?",
        (question_id,),
    ).fetchone()

    if not row:
        raise HTTPException(status_code=404, detail="Clarification question not found")

    q_dict = dict(row)
    check_project_access(conn, q_dict["project_id"], user)

    study_id = q_dict["study_id"]
    reason_text = f"Clarification dismissed: {dismiss_reason}".strip() if dismiss_reason else "Clarification dismissed by reviewer"

    conn.execute(
        """
        UPDATE clarification_questions
        SET status = 'expired',
            final_decision = 'uncertain',
            final_reason_text = ?
        WHERE question_id = ?
        """,
        (reason_text, question_id),
    )

    conn.execute(
        "UPDATE studies SET screening_status = 'uncertain', screening_reason = ? WHERE study_id = ?",
        (reason_text, study_id),
    )

    if hasattr(conn, "commit"):
        conn.commit()

    return {
        "question_id": question_id,
        "study_id": study_id,
        "status": "expired",
        "message": "Clarification dismissed and study marked as uncertain",
    }


@router.get("/studies/{study_id}/clarifications", response_model=list[ClarificationQuestionResponse])
async def get_study_clarifications(
    study_id: str,
    user: Optional[dict] = Depends(get_current_user_optional),
    conn: DBBackend = Depends(get_db),
):
    """Get all clarification questions for a specific study."""
    study = conn.execute("SELECT project_id FROM studies WHERE study_id = ?", (study_id,)).fetchone()
    if not study:
        raise HTTPException(status_code=404, detail="Study not found")

    check_project_access(conn, dict(study)["project_id"], user)

    rows = conn.execute(
        """
        SELECT cq.*, s.title as study_title, s.authors as study_authors, s.abstract as study_abstract
        FROM clarification_questions cq
        LEFT JOIN studies s ON cq.study_id = s.study_id
        WHERE cq.study_id = ?
        ORDER BY cq.created_at DESC
        """,
        (study_id,),
    ).fetchall()

    return [_row_to_clarification_response(row) for row in rows]
