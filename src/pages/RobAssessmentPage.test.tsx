import { render, screen } from '@testing-library/react';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import { beforeEach, expect, it, vi } from 'vitest';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { RobAssessmentPage } from './RobAssessmentPage';
import { api } from '../lib/api';

vi.mock('../components/common/ActualPdfViewer', () => ({
  ActualPdfViewer: () => <div data-testid="pdf-viewer" />,
}));

vi.mock('../lib/api', () => ({
  api: {
    getAssessment: vi.fn(),
    listRobTools: vi.fn(),
    getStudy: vi.fn(),
    listStudies: vi.fn(),
    updateAnswer: vi.fn(),
    updateJudgment: vi.fn(),
  },
  judgmentColor: () => 'bg-[#3a0f34]',
  judgmentLabel: (val: string) => val,
  judgmentDotColor: () => '#3a0f34',
}));

const mockAssessment = {
  assessment_id: "ass_1",
  project_id: "proj_1",
  study_id: "study_birua_2022",
  tool: "rob2",
  overall_judgment: "low",
  tool_definition: {
    key: "rob2",
    name: "RoB 2",
    full_name: "Risk of Bias 2",
    judgment_options: ["low", "high", "some_concerns"],
    domains: [
      {
        key: "d1",
        label: "Domain 1: Randomization Process",
        signaling_questions: [
          {
            key: "q1_1",
            text: "Was the allocation sequence random?",
            response_options: ["yes", "no", "ni"],
          },
        ],
      },
    ],
  },
  domain_judgments: [
    {
      judgment_id: "dj_1",
      domain_key: "d1",
      domain_label: "Domain 1: Randomization Process",
      risk_judgment: "low",
      signaling_answers: [
        {
          answer_id: "sa_1",
          question_key: "q1_1",
          answer: "yes",
          ai_answer: "yes",
          human_verified: 1,
          needs_human_review: 0,
          ai_confidence: 0.98,
          ai_quote: "Sequence generated by computer",
          ai_page: 2,
        },
      ],
    },
  ],
};

function renderPage() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false } },
  });
  return render(
    <QueryClientProvider client={queryClient}>
      <MemoryRouter initialEntries={['/projects/proj_1/rob/ass_1']}>
        <Routes>
          <Route path="/projects/:projectId/rob/:assessmentId" element={<RobAssessmentPage />} />
        </Routes>
      </MemoryRouter>
    </QueryClientProvider>
  );
}

beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(api.getAssessment).mockResolvedValue(mockAssessment);
  vi.mocked(api.listRobTools).mockResolvedValue([]);
  vi.mocked(api.getStudy).mockResolvedValue({ study_id: 'study_birua_2022', title: 'Birua et al. 2022' });
  vi.mocked(api.listStudies).mockResolvedValue([]);
});

it('renders RoB assessment page with domain definitions and signaling questions via O(1) HashMap lookup', async () => {
  renderPage();
  expect(await screen.findByText('Risk of Bias 2 Assessment')).toBeInTheDocument();
  expect(screen.getByText('Was the allocation sequence random?')).toBeInTheDocument();
  expect(screen.getByTestId('pdf-viewer')).toBeInTheDocument();
});
